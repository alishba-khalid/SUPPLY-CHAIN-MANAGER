/**
 * Shared (browser + server) pieces of the chunked smart-import pipeline:
 * flattening an extracted payload into ordered rows, splitting those rows
 * into upload chunks, per-row validation, and the user-facing message
 * formats. No server or DOM dependencies — both sides import this file.
 */
import type {
  ExtractedWarehouse,
  ExtractedSupplier,
  ExtractedProduct,
  ExtractedInventory,
  ExtractedPurchaseOrder,
  ExtractedTransaction,
  ImportCommitPayload,
} from "./types";

export const CHUNK_MAX_ROWS = 2000;
// Leaves headroom under next.config.ts's 2MB serverActions.bodySizeLimit for
// the action envelope. Normal rows are ~100-200 bytes, so 2,000 rows sit far
// below this; the byte cap only kicks in for rows with very long text.
export const CHUNK_MAX_BYTES = 1_500_000;
const MAX_TEXT_LENGTH = 500;

// Dependency order: the commit step writes entities in exactly this order.
export const IMPORT_ENTITIES = [
  "warehouse",
  "supplier",
  "product",
  "inventory",
  "purchase_order",
  "transaction",
] as const;
export type ImportEntity = (typeof IMPORT_ENTITIES)[number];

export const ENTITY_LABELS: Record<ImportEntity, string> = {
  warehouse: "warehouses",
  supplier: "suppliers",
  product: "products",
  inventory: "stock positions",
  purchase_order: "purchase orders",
  transaction: "transactions",
};

export type StagedTransaction = ExtractedTransaction & { importKey: string };

export type StagedRowData =
  | ExtractedWarehouse
  | ExtractedSupplier
  | ExtractedProduct
  | ExtractedInventory
  | ExtractedPurchaseOrder
  | StagedTransaction;

export interface StagedRow {
  entity: ImportEntity;
  /** 1-based position within its entity's list — the "Row N" users see. */
  rowNumber: number;
  data: StagedRowData;
}

export interface ImportChunk {
  index: number;
  rows: StagedRow[];
}

/**
 * The idempotency key for an imported transaction: its content plus its
 * occurrence number among identical rows in the same file. Re-importing the
 * same file reproduces the same keys (so nothing is duplicated), while two
 * genuinely identical movements within one file stay distinct (#1, #2).
 * Plain text rather than a hash, so there's no collision risk.
 */
function withImportKeys(transactions: ExtractedTransaction[]): StagedTransaction[] {
  const seen = new Map<string, number>();
  return transactions.map((t) => {
    const base = `${t.sku}|${t.warehouseCode}|${t.date}|${t.direction}|${t.quantity}`;
    const occurrence = (seen.get(base) ?? 0) + 1;
    seen.set(base, occurrence);
    return { ...t, importKey: `${base}#${occurrence}` };
  });
}

/** Flattens a payload into rows in dependency order. */
export function flattenPayload(payload: Omit<ImportCommitPayload, "skuDuplicateResolution" | "clearExisting">): StagedRow[] {
  const rows: StagedRow[] = [];
  const push = (entity: ImportEntity, items: StagedRowData[]) => {
    items.forEach((data, i) => rows.push({ entity, rowNumber: i + 1, data }));
  };
  // Strip UI-only flags (isAutoGeneratedCode, supplierName…) so they don't
  // bloat the upload.
  push(
    "warehouse",
    payload.warehouses.map(({ code, name, capacityUnits, referenceOnly }) => ({ code, name, capacityUnits, ...(referenceOnly ? { referenceOnly } : {}) }))
  );
  push(
    "supplier",
    payload.suppliers.map(({ supplierId, name, leadTimeDays, email, leadTimeMissing, referenceOnly }) => ({
      supplierId,
      name,
      leadTimeDays,
      email,
      leadTimeMissing: leadTimeMissing ?? false,
      ...(referenceOnly ? { referenceOnly } : {}),
    }))
  );
  push(
    "product",
    payload.products.map(({ sku, name, category, unitCost, supplierId, referenceOnly }) => ({
      sku,
      name,
      category,
      unitCost,
      supplierId,
      ...(referenceOnly ? { referenceOnly } : {}),
    }))
  );
  push("inventory", payload.inventory);
  push("purchase_order", payload.purchaseOrders);
  push("transaction", withImportKeys(payload.transactions));
  return rows;
}

/**
 * Splits rows into chunks of at most `maxRows` rows and roughly `maxBytes`
 * of JSON each. A single row is never split.
 */
export function buildChunks(rows: StagedRow[], maxRows = CHUNK_MAX_ROWS, maxBytes = CHUNK_MAX_BYTES): ImportChunk[] {
  const chunks: ImportChunk[] = [];
  let current: StagedRow[] = [];
  let currentBytes = 0;
  for (const row of rows) {
    const bytes = JSON.stringify(row).length + 1;
    if (current.length > 0 && (current.length >= maxRows || currentBytes + bytes > maxBytes)) {
      chunks.push({ index: chunks.length, rows: current });
      current = [];
      currentBytes = 0;
    }
    current.push(row);
    currentBytes += bytes;
  }
  if (current.length > 0) chunks.push({ index: chunks.length, rows: current });
  return chunks;
}

async function sha256Hex(text: string): Promise<string> {
  const digest = await globalThis.crypto.subtle.digest("SHA-256", new TextEncoder().encode(text));
  return Array.from(new Uint8Array(digest), (b) => b.toString(16).padStart(2, "0")).join("");
}

/**
 * Identifies "the same upload" so a re-selected file can resume. Hashes each
 * chunk separately, then the list of hashes — never builds one giant string
 * for the whole file.
 */
export async function fingerprintChunks(chunks: ImportChunk[], clearExisting: boolean): Promise<string> {
  const chunkHashes: string[] = [];
  for (const chunk of chunks) chunkHashes.push(await sha256Hex(JSON.stringify(chunk.rows)));
  return sha256Hex(`${clearExisting ? "replace" : "merge"}:${chunkHashes.join(",")}`);
}

