/** "Row N, column X: problem", prefixed with the chunk when known. */
export function formatRowError(opts: {
  chunkIndex?: number;
  totalChunks?: number;
  entity: ImportEntity;
  rowNumber: number;
  column: string;
  problem: string;
}): string {
  const where =
    opts.chunkIndex !== undefined
      ? `Chunk ${opts.chunkIndex + 1}${opts.totalChunks ? ` of ${opts.totalChunks}` : ""}, `
      : "";
  return `${where}${ENTITY_LABELS[opts.entity]} row ${opts.rowNumber.toLocaleString("en-US")}, column "${opts.column}": ${opts.problem}`;
}

export function formatLimitNote(rows: number, limit: number): string {
  return `This file has ${rows.toLocaleString("en-US")} rows. Your plan allows ${limit.toLocaleString("en-US")} per import. Split the file or upgrade.`;
}

export function formatLimitHint(limit: number): string {
  return `Up to ${limit.toLocaleString("en-US")} rows per import`;
}

// ---------------------------------------------------------------------------
// Per-row validation (server re-runs this on every chunk — never trusts the
// browser's extractor)
// ---------------------------------------------------------------------------

type Problem = { column: string; problem: string };

function checkText(obj: Record<string, unknown>, key: string, required: boolean): Problem | null {
  const v = obj[key];
  if (v === null || v === undefined || v === "") {
    return required ? { column: key, problem: "is required but empty." } : null;
  }
  if (typeof v !== "string") return { column: key, problem: `expected text, got ${JSON.stringify(v)}.` };
  if (v.length > MAX_TEXT_LENGTH) return { column: key, problem: `is ${v.length} characters long (max ${MAX_TEXT_LENGTH}).` };
  return null;
}

function checkNumber(obj: Record<string, unknown>, key: string, opts: { integer?: boolean; min?: number; optional?: boolean }): Problem | null {
  const v = obj[key];
  if (opts.optional && (v === null || v === undefined)) return null;
  if (typeof v !== "number" || !Number.isFinite(v)) return { column: key, problem: `${JSON.stringify(v)} is not a number.` };
  if (opts.integer && !Number.isInteger(v)) return { column: key, problem: `${v} must be a whole number.` };
  if (opts.min !== undefined && v < opts.min) return { column: key, problem: `${v} is below the minimum of ${opts.min}.` };
  if (Math.abs(v) > 2_000_000_000) return { column: key, problem: `${v} is out of range.` };
  return null;
}

function checkDate(obj: Record<string, unknown>, key: string, required: boolean): Problem | null {
  const v = obj[key];
  if (v === null || v === undefined) return required ? { column: key, problem: "is required but empty." } : null;
  if (typeof v !== "string" || !/^\d{4}-\d{2}-\d{2}$/.test(v) || Number.isNaN(Date.parse(`${v}T00:00:00Z`))) {
    return { column: key, problem: `${JSON.stringify(v)} is not a valid date (expected YYYY-MM-DD).` };
  }
  return null;
}

export function validateRow(row: StagedRow): Problem | null {
  if (!row || typeof row !== "object" || !IMPORT_ENTITIES.includes(row.entity)) {
    return { column: "entity", problem: "unknown row type." };
  }
  if (!Number.isInteger(row.rowNumber) || row.rowNumber < 1) return { column: "row", problem: "invalid row number." };
  const d = row.data as unknown as Record<string, unknown>;
  if (!d || typeof d !== "object") return { column: "data", problem: "row is empty." };

  const checks: (() => Problem | null)[] = [];
  switch (row.entity) {
    case "warehouse":
      checks.push(
        () => checkText(d, "code", true),
        () => checkText(d, "name", true),
        // null = the file gave no capacity; saved as unknown, never a placeholder.
        () => checkNumber(d, "capacityUnits", { integer: true, min: 0, optional: true })
      );
      break;
    case "supplier":
      checks.push(
        () => checkText(d, "supplierId", true),
        () => checkText(d, "name", true),
        () => checkNumber(d, "leadTimeDays", { integer: true, min: 0 }),
        () => checkText(d, "email", false)
      );
      break;
    case "product":
      checks.push(
        () => checkText(d, "sku", true),
        () => checkText(d, "name", true),
        () => checkText(d, "category", false),
        // null = the file has no cost: allowed, never defaulted (the commit
        // keeps an existing product's cost and refuses to create one without).
        () => (d.unitCost === null ? null : checkNumber(d, "unitCost", { min: 0 })),
        () => checkText(d, "supplierId", true)
      );
      break;
    case "inventory":
      checks.push(
        () => checkText(d, "sku", true),
        () => checkText(d, "warehouseCode", true),
        () => checkNumber(d, "quantityOnHand", { integer: true })
      );
      break;
    case "purchase_order":
      checks.push(
        () => checkText(d, "poNumber", true),
        () => checkText(d, "supplierId", true),
        () => checkText(d, "sku", true),
        () => checkNumber(d, "quantity", { integer: true, min: 0 }),
        () => checkNumber(d, "unitPrice", { min: 0 }),
        () => checkDate(d, "orderDate", true),
        () => checkDate(d, "expectedDate", true),
        () => checkDate(d, "receivedDate", false)
      );
      break;
    case "transaction":
      checks.push(
        () => checkText(d, "sku", true),
        () => checkText(d, "warehouseCode", true),
        () => checkNumber(d, "quantity", { integer: true, min: 0 }),
        () => (d.direction === "IN" || d.direction === "OUT" ? null : { column: "direction", problem: `${JSON.stringify(d.direction)} must be IN or OUT.` }),
        () => checkDate(d, "date", true),
        () => checkText(d, "importKey", true)
      );
      break;
  }
  for (const check of checks) {
    const p = check();
    if (p) return p;
  }
  return null;
}

// ---------------------------------------------------------------------------
// Server responses (shared so the browser orchestrator can type them)
// ---------------------------------------------------------------------------

export type ImportCounts = Record<"warehouses" | "suppliers" | "products" | "inventory" | "purchaseOrders" | "transactions", number>;

export type ImportFailure = {
  ok: false;
  error: string;
  /** Present when the failure is the plan's row limit — shown as a neutral note, not an error. */
  limitExceeded?: { rows: number; limit: number };
};

export type BeginResult = { ok: true; sessionId: string; receivedChunks: number[]; resumed: boolean } | ImportFailure;

export type StageResult = { ok: true; receivedChunks: number } | ImportFailure;

export type StatusResult =
  | { ok: true; status: string; totalRows: number; totalChunks: number; receivedChunks: number[] }
  | ImportFailure;

export type CommitResult =
  | {
      ok: true;
      counts: ImportCounts;
      /** Transactions already present from an earlier import of the same rows. */
      duplicateTransactionsSkipped: number;
      /** Demo org: everything ran for real, then was rolled back. */
      simulated: boolean;
    }
  | ImportFailure;
